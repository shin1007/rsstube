-- フォルダごとの重み（毎朝ダイジェストの選抜用）。
--
-- 重要度は要約と同じく全ユーザー共通（0005）なので、記事1件につき1つしか無い。
-- そして基準（新規性・影響範囲・一次情報・実務）は読み手を見ていない一般的な
-- ニュース価値であって、「その人にとって重要か」ではない。読み手ごとに付け直す
-- には要約を購読者ぶん持つことになり、Gemini の呼び出しが購読者数に比例して
-- 増える——0005 でそれが無理だと結論が出ている。
--
-- そこで二層にする。素の重要度は共通のまま置き、**個人の重みを後から掛ける**。
-- フォルダは購読ごとの持ち物（subscriptions.folder_id）なので、ここに重みを
-- 置けばユーザーごとになり、AI の呼び出しは1回も増えない。
--
-- 100 = 素通し。0 = ダイジェストに出さない。未分類のフィードは置き場が無いので
-- 常に 100 として扱う（lib/digest/select.ts）。
--
-- **一覧の並べ替えには効かない。** 一覧は articles.importance を DB 側で
-- order して offset で継ぎ足しており、重みを掛けるとページの境目で記事が
-- 重複・欠落し、「次の記事」も飛ぶ（0007 の罠）。効くのはダイジェストの
-- 選抜だけ、と割り切る。

alter table folders
  add column weight int not null default 100
  check (weight between 0 and 200);

comment on column folders.weight is
  '毎朝ダイジェストの選抜で重要度に掛ける割合(%)。100が素通し、0はこのフォルダを出さない。';
