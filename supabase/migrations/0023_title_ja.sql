-- 外国語の記事に、読む言語での見出しを持たせる。
--
-- ダイジェストの Markdown は「タイトル（原語）＋AI要点（日本語）＋本文（原語）」
-- という作りで、英語のフィードだと中身のほとんどが英語になる。
-- NotebookLM の指示文で「日本語で話して」と頼んでも、渡している素材が
-- 英語ばかりなので音声が英語に引きずられる（実際にそうなった）。
--
-- 要約は既に日本語で作れているので、**同じ呼び出しのついでに見出しも訳させる**。
-- AI の呼び出しは1回も増えない。増えるのは出力トークンが数十ぶんだけ。
--
-- 原語のタイトルは articles.title にそのまま残す。検索と突き合わせに要るのと、
-- 元記事を探すときに原題のほうが確実なため。

alter table summaries
  add column if not exists title_ja text;

comment on column summaries.title_ja is
  '設定言語での見出し。元からその言語ならタイトルと同じでよい。原語は articles.title に残す。';
