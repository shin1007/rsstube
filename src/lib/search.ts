/**
 * PostgREST の or フィルタに入れる検索語の下ごしらえ。
 *
 * `or=(title.ilike.%X%,content_text.ilike.%X%)` という文字列を組み立てる都合上、
 * X にカンマや括弧が入ると式そのものが壊れる（400 が返る）。日本語だと
 * 「〜、〜」「（〜）」は普通に打たれるので、素通しにはできない。
 *
 * 記号で厳密に絞りたい場面は無いので、壊す文字は空白に落として捨てる。
 * % と _ は ilike のワイルドカードなので、これも落として文字通りに扱う。
 */
/**
 * 検索語の上限。
 *
 * 組み立てるのは URL のクエリ文字列で、しかも同じ語を3回
 * （title / title_ja / content_text）繰り返す。実測では**200字を超えると
 * 通らなくなる**——400字あたりは接続そのものが切れ（fetch failed）、
 * 1200字を超えると 400 が返る。どちらも画面は500になり、一覧ごと出なくなる。
 * 検索欄に長文を貼るのは普通にやることなので、黙って切って引く
 * （切った語で引いた結果は、貼った本人が探しているものとだいたい一致する）。
 */
const MAX_TERM = 100;

export function sanitizeSearch(input: string): string {
  return input
    .replace(/[,()"\\%_*]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_TERM)
    .trim();
}
